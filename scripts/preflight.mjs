#!/usr/bin/env node
// Runs before `npm run dev` / `npm start`: checks the certificates and writes
// a local .env with fresh secrets the first time.
import { randomBytes } from 'node:crypto';
import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = join(root, '.env');

const missingCerts = ['localhost.pem', 'localhost-key.pem'].filter((f) => !existsSync(join(root, 'certs', f)));
if (missingCerts.length > 0) {
  console.error(`Missing certs/${missingCerts.join(', certs/')}. Run "npm run certs" first (needs mkcert).`);
  process.exit(1);
}

if (!existsSync(join(root, 'node_modules'))) {
  console.error('Dependencies are not installed. Run "npm install" first.');
  process.exit(1);
}

// Paths are relative to each service's directory, where npm runs its scripts.
const defaults = {
  GATEWAY_SECRET: () => randomBytes(32).toString('base64url'),
  COOKIE_SECRET: () => randomBytes(32).toString('base64url'),
  GATEWAY_CA_FILE: () => (existsSync(join(root, 'certs', 'rootCA.pem')) ? '../../certs/rootCA.pem' : ''),
  DAV_LOG_HEADERS: () => 'false',
};

const existing = existsSync(envFile) ? readFileSync(envFile, 'utf8') : '';
const present = new Set([...existing.matchAll(/^\s*([A-Z0-9_]+)\s*=/gm)].map((m) => m[1]));
const additions = Object.entries(defaults)
  .filter(([key]) => !present.has(key))
  .map(([key, make]) => `${key}=${make()}`)
  .filter((line) => !line.endsWith('='));

if (!existing) {
  writeFileSync(
    envFile,
    `# Local settings for npm run dev. Generated by scripts/preflight.mjs; not committed.\n# Any variable from the README can be set here.\n${additions.join('\n')}\n`,
  );
  console.log('Created .env with fresh secrets.');
} else if (additions.length > 0) {
  appendFileSync(envFile, `${existing.endsWith('\n') ? '' : '\n'}${additions.join('\n')}\n`);
  console.log(`Added ${additions.map((l) => l.split('=')[0]).join(', ')} to .env.`);
}
